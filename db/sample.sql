-- Fictional, disposable data for the local demo. No customer or staff records
-- from the original project are included.
CREATE TABLE beverage_info (
  beverage_info_id integer PRIMARY KEY,
  category text NOT NULL,
  name text NOT NULL,
  price numeric(10, 2) NOT NULL
);

CREATE TABLE inventory (
  inventory_id integer PRIMARY KEY,
  name text NOT NULL,
  stock_level integer NOT NULL
);

CREATE TABLE menu_inventory (
  beverage_info_id integer REFERENCES beverage_info,
  inventory_id integer REFERENCES inventory,
  qt numeric(10, 2) NOT NULL,
  unit text NOT NULL,
  PRIMARY KEY (beverage_info_id, inventory_id)
);

CREATE TABLE toppings (
  inventory_id integer PRIMARY KEY REFERENCES inventory,
  name text NOT NULL
);

CREATE TABLE beverage_toppings (
  beverage_topping_id integer PRIMARY KEY,
  topping_name text NOT NULL
);

CREATE TABLE customer (
  customer_id integer PRIMARY KEY,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text UNIQUE NOT NULL
);

CREATE TABLE employee (
  employee_id integer PRIMARY KEY,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text UNIQUE NOT NULL
);

CREATE TABLE managerlogin (
  id integer PRIMARY KEY,
  name text NOT NULL,
  username text NOT NULL,
  email text UNIQUE NOT NULL,
  password text NOT NULL
);

CREATE TABLE "order" (
  order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer REFERENCES customer,
  total_price numeric(10, 2) NOT NULL,
  month integer,
  week integer,
  date integer,
  hour integer,
  year integer,
  combine_date timestamp NOT NULL DEFAULT now()
);

CREATE TABLE beverage (
  beverage_id integer PRIMARY KEY,
  order_id integer REFERENCES "order",
  beverage_info_id integer REFERENCES beverage_info,
  beverage_name text NOT NULL,
  quantity integer NOT NULL,
  ice_level text,
  sweetness_level text,
  size text,
  price numeric(10, 2) NOT NULL
);

CREATE TABLE daily_total (
  daily_sales numeric(10, 2) DEFAULT 0,
  daily_tax numeric(10, 2) DEFAULT 0,
  new_customers integer DEFAULT 0,
  order_total integer DEFAULT 0,
  customer_total integer DEFAULT 0,
  last_z_report timestamp DEFAULT now()
);

